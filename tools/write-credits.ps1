<#
.SYNOPSIS
  Writes CREDITS.md from the project's own records of where every third-party asset came from.

.DESCRIPTION
  - Assets/ThirdParty/**/source.json: one per Poly Haven / ambientCG asset (tools/fetch-assets.ps1) and per
    Asset Store / Fab item (tools/import-assetstore.ps1).
  - tools/audio-sources.json: every clip cut from the Sonniss bundle (tools/prepare-audio.ps1).
  - The footstep files actually in the project.
  Re-run it after adding or removing assets, so the credits never drift from what is shipped.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File tools/write-credits.ps1
#>
$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$ThirdParty = Join-Path $Root 'Assets/ThirdParty'
$out = New-Object System.Collections.Generic.List[string]
function Line([string]$s = '') { $out.Add($s) }
function Cell([string]$s) { ($s -replace '\|', '\|' -replace '\r?\n', ' ').Trim() }

$sources = Get-ChildItem $ThirdParty -Recurse -Filter source.json | ForEach-Object {
    $j = Get-Content $_.FullName -Raw | ConvertFrom-Json
    $j | Add-Member -NotePropertyName Folder -NotePropertyValue ($_.Directory.FullName.Substring($Root.Length + 1) -replace '\\', '/') -PassThru
}

Line '# Credits'
Line
Line 'Hollowmere uses the third-party assets below. This file is generated by `tools/write-credits.ps1` from the records'
Line 'kept beside each asset (`source.json`), `tools/audio-sources.json` and the files in the project; edit those, not this.'
Line
Line 'Licences are as stated by each source; the links lead to the full terms. CC0 assets need no attribution, but the'
Line 'authors are credited anyway. Asset Store and Fab content is licensed to the account that acquired it: anyone else'
Line 'working on the project needs their own licence for those packs. The project''s own generated art (cobweb, flashlight'
Line 'cookie, flame texture, builder materials and meshes) and the synthesised fallback sounds are original to Hollowmere.'
Line

foreach ($src in 'Poly Haven', 'ambientCG') {
    $items = $sources | Where-Object source -eq $src | Sort-Object { $_.kind }, { $_.name }
    if (-not $items) { continue }
    $site = if ($src -eq 'Poly Haven') { 'https://polyhaven.com' } else { 'https://ambientcg.com' }
    Line "## $src ($($items[0].licence))"
    Line
    Line "Source: <$site>. Licence: [CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/)."
    Line
    Line '| Asset | Kind | Authors | Used for | Link |'
    Line '| --- | --- | --- | --- | --- |'
    foreach ($i in $items) {
        Line ("| {0} | {1} | {2} | {3} | <{4}> |" -f (Cell $i.name), $i.kind, (Cell (($i.authors | ForEach-Object { $_ }) -join ', ')), (Cell $i.use), $i.url)
    }
    Line
}

foreach ($group in ($sources | Where-Object kind -eq 'package' | Group-Object pack)) {
    $first = $group.Group[0]
    Line "## $($first.pack)"
    Line
    Line "Source: $($first.source), <$($first.url)>. Licence: $($first.licence)."
    Line
    Line "Used for: $($first.use)."
    Line
    if ($first.Folder -match 'EssentialFootsteps') {
        Line 'Files used (the rest of the pack is not in the project):'
        Line
        foreach ($d in ($group.Group | Sort-Object id)) {
            $files = Get-ChildItem (Join-Path $Root $d.Folder) -Recurse -Filter *.wav | ForEach-Object Name | Sort-Object
            Line ("- {0}: {1} files ({2} ... {3})" -f $d.id, $files.Count, $files[0], $files[-1])
        }
    } else {
        Line 'Items used (the rest of the pack is not in the project):'
        Line
        foreach ($d in ($group.Group | Sort-Object id)) { Line "- $($d.id)" }
    }
    Line
}

$audio = Get-Content (Join-Path $PSScriptRoot 'audio-sources.json') -Raw | ConvertFrom-Json
Line "## $($audio.source)"
Line
Line "Source: <$($audio.url)>. Licence: $($audio.licence)."
Line
Line 'Clips were cut from the files below (trimmed, looped or levelled by `tools/prepare-audio.ps1`); nothing else from'
Line 'the bundle is in the project.'
Line
Line '| Clip in the project | Publisher / pack | Original file | Used for |'
Line '| --- | --- | --- | --- |'
foreach ($c in ($audio.clips | Sort-Object out)) {
    Line ("| Audio/{0} | {1} | {2} | {3} |" -f $c.out, (Cell $c.pack), (Cell $c.file), (Cell $c.use))
}
Line

Line '## Mixamo'
Line
$mixamo = Join-Path $ThirdParty 'Mixamo'
if ((Test-Path $mixamo) -and (Get-ChildItem $mixamo -Recurse -File -Filter *.fbx)) {
    Line 'Characters and animations from Mixamo (<https://www.mixamo.com>), used under Adobe''s Mixamo terms.'
    Line
    Get-ChildItem $mixamo -Recurse -Filter *.fbx | ForEach-Object { Line "- $($_.Name)" }
} else {
    Line 'None imported yet.'
}
Line

[IO.File]::WriteAllText((Join-Path $Root 'CREDITS.md'), ($out -join "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
Write-Host ("CREDITS.md: {0} third-party records, {1} audio clips." -f $sources.Count, $audio.clips.Count)
