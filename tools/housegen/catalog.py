"""Asset catalog for the Hollowmere village + houses spec.

Every prop/material key used in houses.py / village.py must exist here. Each entry says exactly where the asset
comes from, who downloads it, its licence, the size Claude Code must scale it to, and a paid upgrade for later.

download:
  auto   - Claude Code downloads it itself with tools/fetch-assets.ps1 (Poly Haven / ambientCG, CC0) or
           tools/fetch-sketchfab.ps1 (Sketchfab CC-BY, needs the user's Sketchfab API token once)
  owned  - already on the PC (Assets/ThirdParty, AssetDownloads/*.unitypackage, Sonniss bundle)
  manual - the user must click "download"/"add to library" in a store (Fab / Unity Asset Store) - listed in ASSETS.md
  build  - Claude Code builds it from primitives/ProBuilder in a builder, textured with catalog materials
"""

PH = "polyhaven"; ACG = "ambientcg"; SF = "sketchfab"; OWN = "owned"; BUILD = "procedural"

def m(key, source, id_, dims=None, download="auto", res="1k", licence=None, author=None, note="", upgrade="", tags=()):
    lic = licence or {"polyhaven": "CC0 1.0", "ambientcg": "CC0 1.0", "sketchfab": "CC BY 4.0",
                      "procedural": "own work", "owned": "see CREDITS.md"}.get(source, "")
    return dict(key=key, kind="model", source=source, id=id_, res=res, dims=dims, download=download,
                licence=lic, author=author, note=note, upgrade=upgrade, tags=list(tags))

def t(key, source, id_, use, res="2k", download="auto", note=""):
    lic = "CC0 1.0" if source in (PH, ACG) else "see CREDITS.md"
    return dict(key=key, kind="texture", source=source, id=id_, res=res, use=use, download=download,
                licence=lic, note=note)

